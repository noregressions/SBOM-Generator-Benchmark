def hidden_cell(case, tool, purl):
    """One square per stage the test case has: Y right version, v wrong version, p wrong purl, n not named, · not run."""
    out = []
    for st in STAGES:
        if st not in case["stages"]:
            continue
        doc = next((d for d in case["stages"][st] if d["tool"] == tool), None)
        if doc is None:
            out.append(f'<i class="x" title="{st}: tool not run at this stage">·</i>')
            continue
        hit = doc["hits"].get(purl)
        code = "n" if hit is None else {"exact": "Y", "wrong-version": "v", "wrong-purl": "p"}[hit[0]]
        text = {"Y": "named at the right version", "v": "named at a wrong version", "p": "named under a wrong purl", "n": "not named"}[code]
        out.append(f'<i class="{code}" title="{st}: {text}">{code}</i>')
    return f'<span class="cell">{"".join(out)}</span>'


