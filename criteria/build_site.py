def hidden_cell(case, tool, purl):
    """One square per stage the test case has: Y right version, v wrong version, p wrong purl, n not named, · not run."""
    out = []
    for st in STAGES:
        if st not in case["stages"]:
            continue
        doc = next((d for d in case["stages"][st] if d["tool"] == tool), None)
        if doc is None:
            out.append(f'<i class="x" title="{st}: tool not run at this stage">·</i>')
            continue
        hit = doc["hits"].get(purl)
        code = "n" if hit is None else {"exact": "Y", "wrong-version": "v", "wrong-purl": "p"}[hit[0]]
        text = {"Y": "named at the right version", "v": "named at a wrong version", "p": "named under a wrong purl", "n": "not named"}[code]
        out.append(f'<i class="{code}" title="{st}: {text}">{code}</i>')
    return f'<span class="cell">{"".join(out)}</span>'


LEGEND = ('<p class="muted">One square per stage the test case has, in the order source, artefact, image: '
          '<span class="cell"><i class="Y">Y</i></span> named at the right version, '
          '<span class="cell"><i class="v">v</i></span> wrong version, <span class="cell"><i class="p">p</i></span> wrong purl, '
          '<span class="cell"><i class="n">n</i></span> not named, <span class="cell"><i class="x">·</i></span> tool not run at that stage. '
          'A <b>Y</b> means the purl matched; it does not say why (a shaded jar can be "found" from a leftover metadata file).</p>')


def doc_row(d, first_cell):
    c = d["conformance"]
    return ("<tr>" + first_cell
            + f'<td>{e(d["format"])}</td><td class="num">{d["components"]}</td><td class="num">{d["in_scope"]}</td>'
            + bar(d["shipped_found"], d["shipped_total"])
            + count(len(d["wrong_version"]), bad=True) + count(len(d["wrong_purl"]), bad=True)
            + count(len(d["leaked"]), bad=True) + count(len(d["labelled"]), good=True, extra=d["extra_labelled"])
            + f'<td class="num">{d["hash_ok"]}/{d["hash_emitted"]}</td>'
            + f'<td class="num">{num(c.get("ntia-2021"))}</td><td class="num">{num(c.get("ntia"))}</td><td class="num">{num(c.get("bsi-v21"))}</td>'
            + "</tr>")


DOC_HEADERS = [("Format", ""), ("Comps", "num"), ("In scope", "num"), ("Shipped found", "num"), ("Wrong ver", "num"),
               ("Wrong purl", "num"), ("Leaked", "num"), ("Labelled", "num"), ("Hashes ok", "num"),
               ("NTIA 2021", "num"), ("NTIA/CISA 2026", "num"), ("BSI v2.1", "num")]

COLUMNS = """<ul class="notes">
<li><b>In scope</b>: package components whose purl type is one of the test case's ecosystems (OS packages in images are ignored).</li>
<li><b>Shipped found</b>: recall against what is really in the artefact, at the exact version.</li>
<li><b>Wrong ver</b>: named, but at a version that does not ship. <b>Wrong purl</b>: right name and version under the wrong group, so no advisory database will match it.</li>
<li><b>Leaked</b>: things that do not ship (test, dev, build tooling, <code>provided</code>, BOM imports) listed with nothing a consumer could filter on.</li>
<li><b>Labelled</b>: the same things listed with a scope or property that marks them, which is correct. <code>+N</code> counts further labelled components outside the known list.</li>
<li><b>Hashes ok</b>: hashes that match the real digest of the jar inside the built artefact, over hashes the tool emitted for those jars.</li>
<li><b>NTIA 2021, NTIA/CISA 2026, BSI v2.1</b>: <code>sbomqs compliance</code> totals out of 10. They measure whether the fields are present, not whether the inventory is right.</li>
</ul>"""


def main():
    scores = json.loads((OUT / "scores.json").read_text())
    run = json.loads((OUT / "run.json").read_text()) if (OUT / "run.json").exists() else {}
    cases = {}
    for name, s in scores.items():
        f = ROOT / "testcases" / name / "expected.json"
        if f.exists():
            cases[name] = {"expected": json.loads(f.read_text()), "stages": s["stages"]}

    tools = sorted({d["tool"] for c in cases.values() for docs in c["stages"].values() for d in docs})
    per_tool = {t: [(n, st, d) for n, c in cases.items() for st, docs in c["stages"].items() for d in docs if d["tool"] == t] for t in tools}
    tool_link = lambda t, depth: f'<a href="{"../" * depth}tools/{slug(t)}.html">{e(t)}</a>'
    case_link = lambda n, depth: f'<a href="{"../" * depth}cases/{slug(n)}.html">{e(n)}</a>'

    DOCS.mkdir(exist_ok=True)
    for sub in ("cases", "tools"):
        (DOCS / sub).mkdir(exist_ok=True)
        for old in (DOCS / sub).glob("*.html"):
            old.unlink()
    (DOCS / "style.css").write_text(CSS.lstrip())
    (DOCS / ".nojekyll").write_text("")

    # ------------------------------------------------------------------ index
    B = []
    B.append("<h1>SBOM evaluator</h1>")
    B.append('<p class="lede">Free SBOM generators, run against projects where we know exactly what ships, and scored twice: '
             "on whether the document is true, and on whether it is well formed.</p>")
    n_docs = sum(len(v) for v in per_tool.values())
    meta = [("Test cases", str(len(cases))), ("Tools", str(len(tools))), ("Documents scored", str(n_docs))]
    if run:
        meta += [("Last run", e(run.get("date", ""))), ("Tool image", f'<code>{e(run.get("image", "")[:19])}</code> ({e(run.get("arch", ""))})')]
    B.append('<dl class="meta">' + "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in meta) + "</dl>")

    B.append("<h2>Tools: accuracy next to conformance</h2>")
    B.append("<p>Averages over every document each tool produced. Mean recall is shipped-found over shipped-total, averaged per document. "
             "A high conformance score beside low recall, or beside a large leak count, is a well-formed document about the wrong inventory.</p>")
    rows = []
    ranked = sorted(tools, key=lambda t: -avg([d["shipped_found"] / d["shipped_total"] if d["shipped_total"] else 0 for _, _, d in per_tool[t]]))
    for t in ranked:
        docs = [d for _, _, d in per_tool[t]]
        recall = avg([d["shipped_found"] / d["shipped_total"] if d["shipped_total"] else 0 for d in docs])
        conf = lambda k: num(avg([d["conformance"].get(k) for d in docs]))
        rows.append(f'<tr><td>{tool_link(t, 0)}</td><td class="num">{len(docs)}</td>'
                    f'<td class="num recall"><span class="bar" style="width:{recall * 100:.0f}%"></span><span class="val">{pct(recall)}</span></td>'
                    + count(sum(len(d["wrong_purl"]) for d in docs), bad=True) + count(sum(len(d["leaked"]) for d in docs), bad=True)
                    + count(sum(len(d["labelled"]) for d in docs), good=True)
                    + f'<td class="num">{conf("quality")}</td><td class="num">{conf("ntia-2021")}</td><td class="num">{conf("ntia")}</td><td class="num">{conf("bsi-v21")}</td></tr>')
    B.append(table([("Tool", ""), ("Docs", "num"), ("Mean recall", "num"), ("Wrong purl", "num"), ("Leaked", "num"), ("Labelled", "num"),
                    ("sbomqs quality", "num"), ("NTIA 2021", "num"), ("NTIA/CISA 2026", "num"), ("BSI v2.1", "num")], rows))
    B.append('<p class="muted">Tools run at different stages and on different test cases, so this table is a summary, not a ranking: '
             "a build plugin that only sees source is not competing with a scanner that also reads images. Follow a tool's link for every document it produced.</p>")

    B.append("<h2>Test cases</h2>")
    B.append("<p>Each one is a small project built to hide something from SBOM tools in a specific, documented way, with a hand-written list of what really ends up in the artefact.</p>")
    cards = []
    for n, c in cases.items():
        x = c["expected"]
        mech = sorted({i["hidden"] for i in x["shipped"] + x["not_shipped"] if i.get("hidden")})
        cards.append(f'<a class="card" href="cases/{slug(n)}.html"><b>{e(n)}</b><p>{e(x["title"])}</p>'
                     f'<p>{"".join(f"<span class=chip>{e(m)}</span>" for m in mech)}</p></a>')
    B.append(f'<div class="cards">{"".join(cards)}</div>')

    B.append("<h2>Hidden dependencies: who names them, and where</h2>")
    B.append("<p>The components each test case was built around. These are the ones that reach the artefact, or shape it, without appearing in an ordinary dependency list.</p>")
    B.append(LEGEND)
    rows = []
    for n, c in cases.items():
        for item in c["expected"]["shipped"] + c["expected"]["not_shipped"]:
            if item.get("hidden"):
                rows.append(f'<tr><td>{case_link(n, 0)}</td><td>{e(short(item["purl"]))}</td><td><span class="chip">{e(item["hidden"])}</span></td>'
                            + "".join(f"<td>{hidden_cell(c, t, item['purl'])}</td>" for t in tools) + "</tr>")
    B.append(table([("Test case", ""), ("Component", ""), ("Mechanism", "")] + [(e(t), "") for t in tools], rows))

    B.append("<h2>How to read the scores</h2>")
    B.append("<p><b>Content accuracy</b> asks whether the document names what actually ships, at the right version, without passing off test, dev or build tooling as shipped, and with correct hashes. "
             "It is measured against each test case's ground truth. <b>Baseline conformance</b> asks whether the document carries the fields the published baselines want. "
             "The two disagree, and the disagreement is the point.</p>")
    B.append("<p>Every test case is scanned at up to three stages: <b>source</b> (the checkout, without build outputs or caches), <b>artefact</b> (the built jar, WAR, package or environment) "
             "and <b>image</b> (the container). The hidden mechanisms show up as differences between stages, which is why one scan is never enough.</p>")
    if run.get("versions"):
        B.append("<h2>Tool versions</h2>")
        B.append("<p>Everything runs in one container image built from <code>tools/versions.env</code>, so a report can be reproduced from the commit that holds it.</p>")
        rows = [f"<tr><td>{e(k)}</td><td><code>{e(v)}</code></td></tr>" for k, v in run["versions"].items()]
        B.append(table([("Setting", ""), ("Value", "")], rows))
    (DOCS / "index.html").write_text(page("SBOM evaluator", "\n".join(B)))

    # ------------------------------------------------------------------ one page per test case
    for n, c in cases.items():
        x = c["expected"]
        B = [f"<h1>{e(n)}</h1>", f'<p class="lede">{e(x["title"])}</p>']
        B.append('<dl class="meta">' + f'<dt>Ecosystems</dt><dd>{e(", ".join(x["ecosystems"]))}</dd>'
                 f'<dt>Ships</dt><dd>{len(x["shipped"])} components</dd><dt>Known not to ship</dt><dd>{len(x["not_shipped"])} components</dd>'
                 f'<dt>Stages</dt><dd>{e(", ".join(s for s in STAGES if s in c["stages"]))}</dd>'
                 f'<dt>Source</dt><dd><code>testcases/{e(n)}/</code></dd></dl>')
        hidden = [i for i in x["shipped"] + x["not_shipped"] if i.get("hidden")]
        if hidden:
            B.append("<h2>What it hides</h2>")
            rows = [f'<tr><td>{e(short(i["purl"]))}</td><td><span class="chip">{e(i["hidden"])}</span></td>'
                    f'<td class="wrap">{e(i.get("note") or MECHANISMS.get(i["hidden"], ""))}</td>'
                    + "".join(f"<td>{hidden_cell(c, t, i['purl'])}</td>" for t in tools if any(d["tool"] == t for docs in c["stages"].values() for d in docs)) + "</tr>"
                    for i in hidden]
            used = [t for t in tools if any(d["tool"] == t for docs in c["stages"].values() for d in docs)]
            B.append(LEGEND)
            B.append(table([("Component", ""), ("Mechanism", ""), ("What happens", "")] + [(e(t), "") for t in used], rows))
        B.append("<h2>Every document</h2>")
        rows, notes = [], []
        for st in STAGES:
            if st not in c["stages"]:
                continue
            rows.append(f'<tr class="stage"><td colspan="{len(DOC_HEADERS) + 1}">{st}</td></tr>')
            for d in c["stages"][st]:
                rows.append(doc_row(d, f"<td>{tool_link(d['tool'], 1)}</td>"))
                for key, label in (("wrong_purl", "wrong purl (group guessed)"), ("leaked", "leaked unlabelled")):
                    if d[key]:
                        more = " …" if len(d[key]) > 8 else ""
                        notes.append(f'<li><b>{st} / {e(d["tool"])}</b> {label}: {e(", ".join(short(p) for p in d[key][:8]))}{more}</li>')
                if d["wrong_version"]:
                    notes.append(f'<li><b>{st} / {e(d["tool"])}</b> wrong version: '
                                 + e(", ".join(f"{short(p)} reported as {d['hits'][p][2]}" for p in d["wrong_version"])) + "</li>")
        B.append(table([("Tool", "")] + DOC_HEADERS, rows))
        B.append(COLUMNS)
        if notes:
            B.append("<h3>Details</h3><ul class='notes'>" + "".join(notes) + "</ul>")
        B.append("<h2>Ground truth: what ships</h2>")
        rows = [f'<tr><td><code>{e(i["purl"])}</code></td><td class="wrap">{e(i.get("note", ""))}</td></tr>' for i in x["shipped"]]
        B.append(table([("Component", ""), ("Note", "")], rows))
        (DOCS / "cases" / f"{slug(n)}.html").write_text(page(f"{n} · SBOM evaluator", "\n".join(B), depth=1, crumb=n))

    # ------------------------------------------------------------------ one page per tool
    for t in tools:
        docs = per_tool[t]
        recall = avg([d["shipped_found"] / d["shipped_total"] if d["shipped_total"] else 0 for _, _, d in docs])
        B = [f"<h1>{e(t)}</h1>"]
        B.append('<dl class="meta">' + f"<dt>Documents</dt><dd>{len(docs)}</dd><dt>Mean recall</dt><dd>{pct(recall)}</dd>"
                 f'<dt>Leaked</dt><dd>{sum(len(d["leaked"]) for _, _, d in docs)}</dd>'
                 f'<dt>Formats</dt><dd>{e(", ".join(sorted({d["conformance"].get("spec") or d["format"] for _, _, d in docs})))}</dd></dl>')
        rows = [doc_row(d, f"<td>{case_link(n, 1)}</td><td>{st}</td>") for n, st, d in docs]
        B.append("<h2>Every document</h2>")
        B.append(table([("Test case", ""), ("Stage", "")] + DOC_HEADERS, rows))
        B.append(COLUMNS)
        rows = []
        for n, c in cases.items():
            if not any(name == n for name, _, _ in docs):
                continue
            for i in c["expected"]["shipped"] + c["expected"]["not_shipped"]:
                if i.get("hidden"):
                    rows.append(f'<tr><td>{case_link(n, 1)}</td><td>{e(short(i["purl"]))}</td><td><span class="chip">{e(i["hidden"])}</span></td><td>{hidden_cell(c, t, i["purl"])}</td></tr>')
        if rows:
            B.append("<h2>Hidden dependencies</h2>" + LEGEND)
            B.append(table([("Test case", ""), ("Component", ""), ("Mechanism", ""), ("Named?", "")], rows))
        (DOCS / "tools" / f"{slug(t)}.html").write_text(page(f"{t} · SBOM evaluator", "\n".join(B), depth=1, crumb=t))

    print(f"wrote {DOCS}/ ({1 + len(cases) + len(tools)} pages)")


if __name__ == "__main__":
    main()
