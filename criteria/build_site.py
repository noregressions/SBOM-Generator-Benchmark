def main():
    scores = json.loads((OUT / "scores.json").read_text())
    run = json.loads((OUT / "run.json").read_text()) if (OUT / "run.json").exists() else {}
    cases = {}
    for name, s in scores.items():
        f = ROOT / "testcases" / name / "expected.json"
        if f.exists():
            cases[name] = {"expected": json.loads(f.read_text()), "stages": s["stages"]}

    tools = sorted({d["tool"] for c in cases.values() for docs in c["stages"].values() for d in docs})
    per_tool = {t: [(n, st, d) for n, c in cases.items() for st, docs in c["stages"].items() for d in docs if d["tool"] == t] for t in tools}
    version_of = lambda t: tool_version(t, run.get("versions") or {})     # the versions recorded for this run
    tool_link = lambda t, depth: f'<a href="{"../" * depth}tools/{slug(t)}.html">{e(t)}</a>'
    case_link = lambda n, depth: f'<a href="{"../" * depth}cases/{slug(n)}.html">{e(n)}</a>'

    DOCS.mkdir(exist_ok=True)
    for sub in ("cases", "tools"):
        (DOCS / sub).mkdir(exist_ok=True)
        for old in (DOCS / sub).glob("*.html"):
            old.unlink()
    (DOCS / "style.css").write_text(CSS.lstrip())
    (DOCS / ".nojekyll").write_text("")

    headline = lambda n: (EDITORIAL.get("cases", {}).get(n) or {}).get("headline") or n
    ecosystems = sorted({x for c in cases.values() for x in c["expected"]["ecosystems"]})
    eco_names = {"maven": "Maven", "npm": "npm", "pypi": "pip", "golang": "Go", "cargo": "Cargo", "nuget": "NuGet"}
    eco_text = ", ".join(eco_names.get(x, x) for x in ecosystems[:-1]) + " and " + eco_names.get(ecosystems[-1], ecosystems[-1]) if len(ecosystems) > 1 else eco_names.get(ecosystems[0], ecosystems[0])
    not_covered = [v for k, v in (("gradle", "Gradle"), ("cargo", "Rust"), ("nuget", ".NET"), ("golang", "Go")) if k not in ecosystems]
    generators = sorted({VARIANTS.get(t, (t,))[0] for t in tools})
    n_docs = sum(len(v) for v in per_tool.values())
    repo = EDITORIAL["repository"]
    disclosure = f'<div class="note"><p><b>Disclosure.</b> {e(EDITORIAL["disclosure"])}</p></div>'
    if run.get("sbom_plus_local"):
        disclosure += ('<div class="note"><p><b>Unpublished build.</b> This run used a local build of SBOM+ that is not the one on Maven Central, '
                       "so its results cannot be reproduced from the published plugin.</p></div>")

    # ------------------------------------------------------------------ findings: evidence chosen from this run
    def all_docs():
        for n, c in cases.items():
            for st, docs in c["stages"].items():
                for d in docs:
                    yield n, st, d

    def tl(t):   # a tool name, with its version, linked
        v = version_of(t)
        return f'<a href="tools/{slug(t)}.html">{e(display(t))}</a>' + (f" {e(v)}" if v else "")

    def cl(n):
        return f'<a href="cases/{slug(n)}.html">{e(n)}</a>'

    vulns = json.loads((OUT / "vulns.json").read_text()) if (OUT / "vulns.json").exists() else {}
    evidence = {}
    highlight = None
    # conformance: the best NTIA 2021 score that sits beside the most leaked components
    scored = [(n, st, d) for n, st, d in all_docs() if d["conformance"].get("ntia-2021") is not None and d["leaked"]]
    if scored:
        top = max(d["conformance"]["ntia-2021"] for _, _, d in scored)
        n, st, d = max((x for x in scored if x[2]["conformance"]["ntia-2021"] >= top - 0.5), key=lambda x: len(x[2]["leaked"]))
        highlight = (n, st, d["tool"])
        evidence["conformance"] = dict(case=cl(n), stage=st, tool=tl(d["tool"]), score=num(d["conformance"]["ntia-2021"]),
                                       leaked=len(d["leaked"]), found=d["shipped_found"], total=d["shipped_total"])
    # stage: on one test case, the tool whose recall falls furthest from source to image, and the one that rises furthest
    best = None
    for n, c in cases.items():
        if not all(st in c["stages"] for st in STAGES):
            continue
        by = {}
        for st in STAGES:
            for d in c["stages"][st]:
                if d["tool"] not in VARIANTS:
                    by.setdefault(d["tool"], {})[st] = d["shipped_found"]
        full = {t: v for t, v in by.items() if len(v) == 3}
        if len(full) < 2:
            continue
        down = max(full, key=lambda t: full[t]["source"] - full[t]["image"])
        up = max(full, key=lambda t: max(full[t]["artefact"], full[t]["image"]) - full[t]["source"])
        spread = (full[down]["source"] - full[down]["image"]) + (max(full[up]["artefact"], full[up]["image"]) - full[up]["source"])
        if down != up and (best is None or spread > best[0]):
            total = c["stages"]["source"][0]["shipped_total"]
            best = (spread, dict(case=cl(n), total=total, tool_a=tl(down), tool_b=tl(up),
                                 **{f"a_{st}": full[down][st] for st in STAGES}, **{f"b_{st}": full[up][st] for st in STAGES}))
    if best:
        evidence["stage"] = best[1]
    # bundling: every component hidden by bundling, and how often a tool named it early and late
    tally = {"source": [0, 0], "later": [0, 0]}
    names = []
    for n, c in cases.items():
        for item in c["expected"]["shipped"] + c["expected"]["not_shipped"]:
            if "bundled" not in (item.get("hidden") or ""):
                continue
            names.append(short(item["purl"]).split("@")[0])
            for st, docs in c["stages"].items():
                for d in docs:
                    if d["tool"] in VARIANTS:
                        continue
                    slot = tally["source" if st == "source" else "later"]
                    slot[1] += 1
                    hit = d["hits"].get(item["purl"])
                    slot[0] += 1 if hit and hit[0] == "exact" else 0
    if names and tally["later"][1]:
        evidence["bundling"] = dict(count=len(names), names=e(", ".join(names)), source_hit=tally["source"][0], source_tries=tally["source"][1],
                                    later_hit=tally["later"][0], later_tries=tally["later"][1])

    # advisories: the hidden shipped component with the most advisories, and the SBOM with the most false alarms
    best = None
    for n, v in (vulns.get("cases") or {}).items():
        per = {}
        for r in v["reference"]:
            if r.get("hidden"):
                per.setdefault(r["purl"], set()).add(r["id"])
        for purl, ids in per.items():
            if best is None or len(ids) > len(best[2]):
                best = (n, purl, ids)
    worst = max(((len(r["false_alarms"]), n, st, r["tool"]) for n, v in (vulns.get("cases") or {}).items() for st, rows in v["stages"].items()
                 for r in rows if r["tool"] not in VARIANTS), default=None)
    if best and worst and worst[0]:
        n, purl, ids = best
        tally = {"source": [0, 0], "later": [0, 0]}
        for st, rows in vulns["cases"][n]["stages"].items():
            for r in rows:
                if r["tool"] in VARIANTS:
                    continue
                slot = tally["source" if st == "source" else "later"]
                slot[1] += 1
                slot[0] += 0 if any(m[0] == purl for m in r["missed"]) else 1
        evidence["advisories"] = dict(component=e(short(purl)), case=cl(n), n=len(ids), source_hit=tally["source"][0], source_docs=tally["source"][1],
                                      later_hit=tally["later"][0], later_docs=tally["later"][1], fa_tool=tl(worst[3]), fa_stage=worst[2],
                                      fa_case=cl(worst[1]), fa_count=worst[0])

    # ------------------------------------------------------------------ index: the question, the findings, where to go next
    B = [f'<h1 class="hero">{e(EDITORIAL["question"])}</h1>']
    B.append(f'<p class="thesis">{e(EDITORIAL["proposition"])}</p>')
    B.append(f"<p>The SBOM Generator Index runs {len(generators)} free SBOM generators against {len(cases)} small projects built to hide "
             "a dependency in a specific, documented way. For each project we know what ends up in the shipped artefact, so every SBOM can be "
             "checked against it. Each document gets two scores: <b>content accuracy</b> (is it true?) and <b>baseline conformance</b> "
             "(does it have the fields the published baselines ask for?).</p>")
    meta = [("Generators", str(len(generators))), ("Test cases", str(len(cases))), ("SBOMs scored", str(n_docs))]
    if run:
        meta += [("Run on", e(run.get("date", ""))), ("Tool versions", '<a href="methodology.html#versions">pinned, listed under Methodology</a>')]
    B.append('<dl class="meta">' + "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in meta) + "</dl>")

    B.append("<h2>What the run shows</h2>")
    B.append(f"<p>{'Four' if 'advisories' in evidence else 'Three'} findings, each with the measurement behind it. <b>Observed</b> is what this run recorded. <b>Likely reason</b> is our reading of why, "
             "which the data supports but does not prove.</p>")
    for f in EDITORIAL["findings"]:
        ev = evidence.get(f["id"])
        if not ev:
            continue
        B.append(f'<div class="finding"><h3>{e(f["title"])}</h3>'
                 f'<p><span class="label">Observed</span> {f["observed"].format(**ev)}</p>'
                 f'<p><span class="label">Likely reason</span> {e(f["explanation"])}</p>'
                 f'<p><span class="label">What it costs</span> {e(f["consequence"])}</p></div>')

    B.append(accuracy_scatter(cases, highlight))

    B.append("<h2>Explore</h2>")
    B.append('<div class="cards">'
             '<a class="card" href="results.html"><b>Results by stage</b><p>Tools compared like for like: source, artefact and image, each against the same test cases.</p></a>'
             '<a class="card" href="security.html"><b>Security view</b><p>Which advisories each SBOM would raise: the ones that apply, the ones it misses, and the false alarms.</p></a>'
             '<a class="card" href="results.html#hidden"><b>Hidden dependencies</b><p>Component by component: which tool named each hidden dependency, and at which stage.</p></a>'
             '<a class="card" href="methodology.html"><b>Methodology</b><p>How ground truth was established, how the scores are counted, and what the benchmark cannot tell you.</p></a>'
             '<a class="card" href="methodology.html#run"><b>Run it yourself</b><p>Reproduce this run, or point the same tools at your own project.</p></a></div>')

    B.append("<h2>Test cases</h2>")
    B.append("<p>Each one is a small project built to hide something from SBOM tools, with a hand-written list of what really ends up in the artefact.</p>")
    cards = []
    for n, c in cases.items():
        x = c["expected"]
        mech = sorted({i["hidden"] for i in x["shipped"] + x["not_shipped"] if i.get("hidden")})
        cards.append(f'<a class="card" href="cases/{slug(n)}.html"><b>{e(headline(n))}</b><p>{e(x["title"])}</p><p><code>{e(n)}</code></p>'
                     f'<p>{"".join(f"<span class=chip>{e(m)}</span>" for m in mech)}</p></a>')
    B.append(f'<div class="cards">{"".join(cards)}</div>')

    B.append("<h2>Before you rely on this</h2>")
    B.append(disclosure)
    B.append(f'<p>The benchmark is small: {len(cases)} test cases covering {eco_text}. It measures how tools cope with specific hiding mechanisms, '
             'not how they do on a typical project, and it does not name a best tool. <a href="methodology.html#limits">The limits are listed in full</a> under Methodology. '
             f'Everything is in the <a href="{e(repo)}">repository</a>: the test cases, every generated SBOM, the scores and the code that produced them.</p>')
    (DOCS / "index.html").write_text(page("SBOM Generator Index", "\n".join(B)))

    # ------------------------------------------------------------------ results: one table per stage, like for like
    B = ["<h1>Results by stage</h1>"]
    B.append('<p class="lede">Tools are compared only with tools that scanned the same kind of input. There is no overall score and no ranking.</p>')
    B.append('<div class="note"><p><b>Read this first.</b> A tool that reads a build cannot see inside a finished image, and a scanner cannot ask a build what it resolved. '
             "Tools are also run only on the ecosystems they support, so their totals cover different test cases. Each table says which. "
             "Rows are in alphabetical order within each group.</p></div>")
    stage_text = {"source": "The checkout, with build outputs and dependency caches removed. Ecosystem-native tools run the build, or read what it wrote down.",
                  "artefact": "The built jar, WAR, installed package or Python environment: the thing that is shipped.",
                  "image": "The container image built from the test case's Dockerfile. Only application components are counted; operating-system packages are left out."}
    for st in STAGES:
        st_cases = [n for n, c in cases.items() if st in c["stages"]]
        if not st_cases:
            continue
        st_tools = sorted({d["tool"] for n in st_cases for d in cases[n]["stages"][st]})
        B.append(f'<h2 id="{st}">{st.capitalize()} stage</h2><p>{stage_text[st]}</p>')
        headers = [("Tool", ""), ("Version", "")] + [(e(n), "num") for n in st_cases] + [("Total found", "num"), ("Cases", "num"),
                   ("Wrong purl", "num"), ("Leaked", "num"), ("Labelled", "num"), ("NTIA 2021", "num"), ("NTIA/CISA 2026", "num"), ("BSI v2.1", "num")]
        rows = []
        for kind, label, blurb in KINDS:
            group = [t for t in st_tools if kind_of(t) == kind]
            if not group:
                continue
            rows.append(f'<tr class="kind"><td colspan="{len(headers)}"><b>{label}.</b> {blurb}</td></tr>')
