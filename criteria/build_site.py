def component_grid(name, case, repo):
    """Rows are components, columns are tools grouped by stage. Each cell is a button; the script below shows what is behind it."""
    exp = case["expected"]
    stages = [st for st in STAGES if st in case["stages"]]
    cols = [(st, d) for st in stages for d in case["stages"][st]]
    top = '<tr class="groups"><th class="comp"></th>' + "".join(f'<th class="stage" colspan="{len(case["stages"][st])}">{st}</th>' for st in stages) + "</tr>"
    head = '<tr><th class="comp">Component</th>' + "".join(f'<th class="tool"><span>{e(display(d["tool"]))}</span></th>' for _, d in cols) + "</tr>"

    def row(item, ships):
        cells = []
        prev = None
        for st, d in cols:
            hit = d["hits"].get(item["purl"])
            if ships:
                code = "n" if hit is None else {"exact": "Y", "wrong-version": "v", "wrong-purl": "p"}[hit[0]]
            else:
                code = "o" if hit is None else ("L" if hit[1] else "X")
            reported = (hit[3] if hit and len(hit) > 3 else "") or ""
            where = (f'{repo}/blob/main/criteria/output/{name}/{st}/{d["file"]}' if st != "image" else "")
            cells.append(f'<td class="{"first" if st != prev else ""}"><button type="button" data-tool="{e(display(d["tool"]))}" data-stage="{st}" data-state="{e(GRID_STATES[code])}" '
                         f'data-expected="{e(item["purl"])}" data-reported="{e(reported)}" data-label="{e((hit[1] if hit else "") or "")}" data-sbom="{e(where)}" '
                         f'title="{e(display(d["tool"]))}, {st}: {e(GRID_STATES[code])}"><span class="cell"><i class="{code}">{"·" if code == "o" else code}</i></span></button></td>')
            prev = st
        tag = f' <span class="chip">{e(item["hidden"])}</span>' if item.get("hidden") else ""
        return f'<tr><td class="comp">{e(short(item["purl"]))}{tag}</td>{"".join(cells)}</tr>'

    rows = [f'<tr class="sep"><td colspan="{len(cols) + 1}"><b>Ships.</b> In the artefact, including components that were shaded or bundled on the way in.</td></tr>']
    rows += [row(i, True) for i in exp["shipped"]]
    build = [i for i in exp["not_shipped"] if i.get("hidden")]
    if build:
        rows.append(f'<tr class="sep"><td colspan="{len(cols) + 1}"><b>Present in the build, absent from the artefact.</b> Plugins and their payloads, imported BOMs, and dependencies the build file requires but the artefact never contains. '
                    "Listing one is right when it is marked as not shipping.</td></tr>")
        rows += [row(i, False) for i in build]
    legend = ('<p class="muted">Ships: <span class="cell"><i class="Y">Y</i></span> exact version, <span class="cell"><i class="v">v</i></span> wrong version, '
              '<span class="cell"><i class="p">p</i></span> wrong group or namespace, <span class="cell"><i class="n">n</i></span> not named. '
              'Does not ship: <span class="cell"><i class="L">L</i></span> listed and marked, <span class="cell"><i class="X">X</i></span> listed unmarked, '
              '<span class="cell"><i class="o">·</i></span> not listed. A tool appears under a stage only if it was run there, so an empty column never stands for a miss. '
              "Select a cell to see what is behind it.</p>")
    return (legend + '<div id="cellinfo" aria-live="polite"><p class="muted">Select a cell.</p></div>'
            + f'<div class="scroll"><table class="grid"><thead>{top}{head}</thead><tbody>{"".join(rows)}</tbody></table></div>')


