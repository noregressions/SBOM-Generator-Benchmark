                docs = {n: next((d for d in cases[n]["stages"][st] if d["tool"] == t), None) for n in st_cases}
                ran = [d for d in docs.values() if d]
                cells = "".join(bar(d["shipped_found"], d["shipped_total"]) if d else
                                '<td class="notrun" title="not run on this test case at this stage">–</td>' for d in docs.values())
                conf = lambda k: num(avg([d["conformance"].get(k) for d in ran]))
