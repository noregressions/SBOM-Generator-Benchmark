#!/usr/bin/env python3
"""Build the static report site (docs/) from the last evaluation.

Reads criteria/output/scores.json, criteria/output/run.json and testcases/*/expected.json; writes docs/index.html,
docs/cases/<test case>.html, docs/tools/<tool>.html and docs/style.css. Standard library only. The site is plain
HTML with relative links, so GitHub Pages can serve docs/ from the main branch with no build step.

Usage: build_site.py            (normally run by ./evaluate after score.py)
"""
import html, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "criteria" / "output"
DOCS = ROOT / "docs"
STAGES = ["source", "artefact", "image"]
PROFILES = [("ntia-2021", "NTIA 2021"), ("ntia", "NTIA/CISA 2026"), ("bsi-v21", "BSI v2.1"), ("fsct", "FSCT v3")]
MECHANISMS = {
    "shaded": "relocated into another jar by the shade plugin",
    "bundled": "compiled into a JavaScript bundle; no package boundary survives",
    "plugin-realm": "runs inside a Maven plugin's classloader, never in the project's dependency graph",
    "plugin-realm+bundled": "enters through a Maven plugin and is then bundled into a static asset",
    "bom-import": "an imported BOM that decides versions but ships nothing",
    "prepack-generated": "written by an npm lifecycle hook when the package was packed",
    "pep517-generated": "generated by a PEP 517 build backend at install time",
}
e = html.escape


def short(purl):
    """pkg:maven/group/name@1.0 -> name@1.0"""
    body = purl.split("?")[0]
    name, _, ver = body.rpartition("@") if "@" in body.split("/")[-1] else (body, "", "")
    return name.rsplit("/", 1)[-1] + ("@" + ver if ver else "")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def pct(x):
    return f"{x:.0%}"


def avg(values):
    values = [v for v in values if v is not None]
    return sum(values) / len(values) if values else None


def num(v, digits=1):
    return "–" if v is None else f"{v:.{digits}f}"


def bar(found, total):
    """Recall as 'n/m' with a proportional bar behind it."""
    share = found / total if total else 0
    return (f'<td class="num recall"><span class="bar" style="width:{share * 100:.0f}%"></span>'
            f'<span class="val">{found}/{total}</span></td>')


def count(n, bad=False, good=False, extra=0):
    cls = "num" + (" bad" if bad and n else "") + (" good" if good and n else "")
    plus = f'<span class="muted">+{extra}</span>' if extra else ""
    return f'<td class="{cls}">{n}{plus}</td>'


def page(title, body, depth=0, crumb=None):
    up = "../" * depth
    nav = f'<a href="{up}index.html">SBOM evaluator</a>' + (f' <span class="muted">/</span> {e(crumb)}' if crumb else "")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title>
<link rel="stylesheet" href="{up}style.css">
</head>
<body>
<header><nav>{nav}</nav></header>
<main>
{body}
</main>
<footer>Generated by <code>criteria/build_site.py</code> from <code>criteria/output/scores.json</code>. Do not edit by hand; run <code>./evaluate</code>.</footer>
</body>
</html>
"""


def table(headers, rows, cls=""):
    head = "".join(f'<th class="{c}">{h}</th>' for h, c in headers)
    return f'<div class="scroll"><table class="{cls}"><thead><tr>{head}</tr></thead><tbody>{"".join(rows)}</tbody></table></div>'


