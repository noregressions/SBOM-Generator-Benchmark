def short(purl):
    """pkg:maven/group/name@1.0 -> name@1.0. A Go module keeps its whole path, because the last segment alone (text, v3) names nothing."""
    if purl.startswith("pkg:golang/") and "/" in purl[len("pkg:golang/"):]:
        return purl.split("?")[0][len("pkg:golang/"):].replace("%2B", "+")
    body = purl.split("?")[0]
    name, _, ver = body.rpartition("@") if "@" in body.split("/")[-1] else (body, "", "")
    return name.rsplit("/", 1)[-1] + ("@" + ver if ver else "")


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def pct(x):
    return f"{x:.0%}"


def avg(values):
    values = [v for v in values if v is not None]
    return sum(values) / len(values) if values else None


def num(v, digits=1):
    return "–" if v is None else f"{v:.{digits}f}"


def bar(found, total):
    """Recall as 'n/m' with a proportional bar behind it."""
    share = found / total if total else 0
    return (f'<td class="num recall"><span class="bar" style="width:{share * 100:.0f}%"></span>'
            f'<span class="val">{found}/{total}</span></td>')


def count(n, bad=False, good=False, extra=0):
    cls = "num" + (" bad" if bad and n else "") + (" good" if good and n else "")
    plus = f'<span class="muted">+{extra}</span>' if extra else ""
    return f'<td class="{cls}">{n}{plus}</td>'


